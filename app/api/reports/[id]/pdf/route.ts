import { NextResponse } from "next/server";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { getCurrentProfile } from "@/lib/supabaseAuth";
import { getSupabaseAdmin } from "@/lib/supabaseAdmin";

export async function GET(
  request: Request,
  context: { params: Promise<{ id: string }> }
) {
  const profile = await getCurrentProfile();

  if (!profile || !["admin","student","parent"].includes(profile.role)) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  try {
    const { id } = await context.params;
    const sb = getSupabaseAdmin();

    const { data: report, error } = await sb
      .from("monthly_reports")
      .select(`
        *,
        students(full_name,student_code,country),
        teachers(full_name),
        enrollments(courses(name_en,name_ur))
      `)
      .eq("id", id)
      .maybeSingle();

    if (error) throw error;
    if (!report) return NextResponse.json({ error: "Report not found" }, { status: 404 });

    // Role ownership checks
    if (profile.role === "student") {
      const { data: student } = await sb
        .from("students")
        .select("id")
        .eq("user_id", profile.id)
        .maybeSingle();

      if (!student || student.id !== report.student_id) {
        return NextResponse.json({ error: "Forbidden" }, { status: 403 });
      }
    }

    if (profile.role === "parent") {
      const { data: parent } = await sb
        .from("parents")
        .select("id")
        .eq("user_id", profile.id)
        .maybeSingle();

      const { data: child } = await sb
        .from("students")
        .select("id")
        .eq("id", report.student_id)
        .eq("parent_id", parent?.id || "")
        .maybeSingle();

      if (!child) {
        return NextResponse.json({ error: "Forbidden" }, { status: 403 });
      }
    }

    const pdf = await PDFDocument.create();
    const page = pdf.addPage([595.28, 841.89]);

    const regular = await pdf.embedFont(StandardFonts.Helvetica);
    const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

    const deep = rgb(0.04, 0.24, 0.19);
    const gold = rgb(0.74, 0.55, 0.18);
    const text = rgb(0.15, 0.15, 0.15);
    const muted = rgb(0.42, 0.42, 0.42);

    let y = 790;

    page.drawText("Farooqi Online Quran Academy", {
      x: 50, y, size: 20, font: bold, color: deep
    });

    y -= 28;

    page.drawText("Monthly Progress Report", {
      x: 50, y, size: 15, font: bold, color: gold
    });

    y -= 35;

    const line = (label: string, value: string) => {
      page.drawText(label, { x: 50, y, size: 10, font: bold, color: deep });
      page.drawText(value || "-", { x: 190, y, size: 10, font: regular, color: text });
      y -= 20;
    };

    line("Student", `${report.students?.full_name || ""} (${report.students?.student_code || ""})`);
    line("Month", String(report.report_month).slice(0, 7));
    line("Course", report.enrollments?.courses?.name_en || "-");
    line("Teacher", report.teachers?.full_name || "-");
    line("Total Classes", String(report.total_classes));
    line("Present", String(report.present_classes));
    line("Absent", String(report.absent_classes));
    line("Late", String(report.late_classes));
    line("Leave", String(report.leave_classes));
    line("Attendance", `${report.attendance_percentage}%`);
    line("Average Performance", report.average_performance ? `${report.average_performance}/5` : "-");

    y -= 10;

    const block = (heading: string, value?: string | null) => {
      if (!value) return;

      page.drawText(heading, {
        x: 50, y, size: 11, font: bold, color: deep
      });

      y -= 17;

      const clean = String(value).replace(/[^\x20-\x7E]/g, " ");
      const words = clean.split(/\s+/);
      let current = "";

      for (const word of words) {
        const test = current ? current + " " + word : word;

        if (regular.widthOfTextAtSize(test, 9) > 490) {
          page.drawText(current, { x: 50, y, size: 9, font: regular, color: muted });
          y -= 14;
          current = word;
        } else {
          current = test;
        }
      }

      if (current) {
        page.drawText(current, { x: 50, y, size: 9, font: regular, color: muted });
        y -= 14;
      }

      y -= 10;
    };

    block("Progress Summary", report.progress_summary);
    block("Strengths", report.strengths);
    block("Areas to Improve", report.improvement_areas);
    block("Next Month Goal", report.next_month_goal);
    block("Teacher Comment", report.teacher_comment);

    page.drawText("Generated by Farooqi Quran Portal", {
      x: 50, y: 35, size: 8, font: regular, color: muted
    });

    const bytes = await pdf.save();

    return new NextResponse(bytes as BodyInit, {
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="farooqi-progress-${String(report.report_month).slice(0,7)}.pdf"`,
      },
    });
  } catch (error) {
    return NextResponse.json(
      { error: error instanceof Error ? error.message : "Could not generate PDF." },
      { status: 500 }
    );
  }
}
